import archiver from 'archiver';
import { getModVersions, downloadModFile } from './modrinth.js';

/**
 * Create a zip file containing all mods for a pack
 * @returns {ReadableStream} The zip stream
 */
export async function createModPackZip(modIds, options = {}) {
  const {
    packName = 'MineSmith Pack',
    minecraftVersion = '1.20.1',
    description = 'A custom modpack built with MineSmith',
  } = options;

  const archive = archiver('zip', { zlib: { level: 1 } }); // Fast compression for jar files

  // Add manifest
  const manifest = {
    name: packName,
    description,
    minecraftVersion,
    createdAt: new Date().toISOString(),
    generator: 'MineSmith v1.0.0',
    mods: [],
  };

  // Download each mod and add to zip
  for (const modId of modIds) {
    try {
      const versions = await getModVersions(modId, { minecraftVersion });

      if (!versions || versions.length === 0) {
        // Try without version filter
        const allVersions = await getModVersions(modId);
        if (allVersions && allVersions.length > 0) {
          const latest = allVersions[0];
          await addModToArchive(archive, latest, manifest);
        }
        continue;
      }

      const latest = versions[0];
      await addModToArchive(archive, latest, manifest);
    } catch {
      // Skip failed mods silently
    }
  }

  // Add README.md
  const readmeContent = generateReadme(packName, description, minecraftVersion, manifest.mods);
  archive.append(readmeContent, { name: 'README.md' });

  // Add manifest.json
  archive.append(JSON.stringify(manifest, null, 2), { name: 'manifest.json' });

  // Add installation instructions
  const installGuide = generateInstallGuide(minecraftVersion, manifest.mods.length);
  archive.append(installGuide, { name: 'INSTALL.txt' });

  archive.finalize();

  return archive;
}

/**
 * Download a mod's jar file and add it to the archive
 */
async function addModToArchive(archive, versionData, manifest) {
  const file = versionData.files?.[0];
  if (!file) return;

  const { buffer, filename } = await downloadModFile(file.url);

  // Add jar to mods/ folder
  archive.append(buffer, { name: `mods/${filename}` });

  // Track in manifest
  manifest.mods.push({
    filename,
    modId: versionData.project_id,
    modLoader: versionData.loaders?.[0] || 'unknown',
    minecraftVersions: versionData.game_versions || [],
    hashes: file.hashes || {},
  });
}

/**
 * Generate a README.md for the pack
 */
function generateReadme(name, description, mcVersion, mods) {
  return `# ${name}

> ${description}

**Minecraft Version:** ${mcVersion}  
**Total Mods:** ${mods.length}  
**Generated by:** MineSmith (minesmith.app)

## Mod List

${mods.map((m, i) => `${i + 1}. **${m.filename}** (${m.modLoader})`).join('\n')}

## How to Install

1. Make sure you have Minecraft ${mcVersion} installed
2. Install a mod loader (Forge or Fabric) for ${mcVersion}
3. Copy all files from the \`mods/\` folder to your Minecraft \`mods/\` folder
4. Launch Minecraft and enjoy!

## Links

- Built with [MineSmith](https://minesmith.app)
- Mods sourced from [Modrinth](https://modrinth.com)
`;
}

/**
 * Generate installation instructions
 */
function generateInstallGuide(mcVersion, modCount) {
  return `MineSmith Modpack Installation Guide
=====================================

Minecraft Version: ${mcVersion}
Total Mods: ${modCount}

QUICK START:
1. Install Minecraft ${mcVersion}
2. Install Forge or Fabric for ${mcVersion}
3. Open your Minecraft folder:
   - Windows: %APPDATA%\\.minecraft
   - Mac: ~/Library/Application Support/minecraft
   - Linux: ~/.minecraft
4. Copy all files from the "mods/" folder into your .minecraft/mods/ folder
5. Launch Minecraft with the correct mod loader profile

NEED HELP?
- Visit: https://modrinth.com
- MineSmith: https://minesmith.app
`;
}
